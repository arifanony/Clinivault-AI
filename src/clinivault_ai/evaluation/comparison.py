"""Controlled-comparison runner: baseline vs term-weighted vs semantic.

Evaluation-only. Reuses the frozen 21-case benchmark definitions
(``cases.CASES``), the frozen metric functions (``metrics``), and the
production search/VectorStore components UNCHANGED; only the embedding
provider is substituted. No production wiring is touched.
"""

from __future__ import annotations

import json
from pathlib import Path

from .cases import CASES, BenchmarkCase
from . import metrics

PARSED = Path("data") / "parsed" / "stage-1-clean-baseline-corpus"
TOP_K = 5


def _chunks_for(document_id: str) -> dict:
    from clinivault_ai.chunking import chunk_pages, default_config

    parsed = json.loads((PARSED / document_id / f"{document_id}.parsed.json")
                        .read_text(encoding="utf-8"))
    return chunk_pages(parsed, default_config())


def _store_for(document_id: str, provider):
    """Build a VectorStore with vectors freshly generated by ``provider``."""
    from clinivault_ai.embedding.embedder import generate_embeddings
    from clinivault_ai.retrieval.store import VectorStore

    chunk_output = _chunks_for(document_id)
    artifact = generate_embeddings(chunk_output, provider)
    return VectorStore.from_artifacts(artifact, chunk_output)


def run_with_provider(cases: tuple[BenchmarkCase, ...] = CASES,
                      provider_factory=None, top_k: int = TOP_K) -> dict:
    """Run every case with a fresh embedding provider per document.

    ``provider_factory(document_id, chunk_texts)`` must return an
    EmbeddingProvider (the term-weighted provider is fitted per document).
    For providers that need no per-document fit, pass a factory that ignores
    the arguments.
    """
    from clinivault_ai.retrieval.search import search

    stores: dict[str, tuple[object, object]] = {}
    results = []
    for case in cases:
        if case.document_id not in stores:
            chunk_output = _chunks_for(case.document_id)
            provider = provider_factory(
                case.document_id, [c["text"] for c in chunk_output["chunks"]])
            store = _store_for(case.document_id, provider)
            stores[case.document_id] = (store, provider)
        store, provider = stores[case.document_id]

        class _QueryAdapter:
            """Present the query side of the provider to search()."""

            name = provider.name
            dimension = provider.dimension

            @staticmethod
            def embed_texts(texts: list[str]) -> list[list[float]]:
                if hasattr(provider, "embed_query"):
                    return [provider.embed_query(texts[0])]
                return provider.embed_texts(texts)

        top = search(store, case.query, _QueryAdapter, top_k)
        ranked = [r["chunk_id"] for r in top]
        rel = list(case.expected_chunk_ids)

        first_rank = metrics.first_relevant_rank(ranked, rel)
        record = {
            "case_id": case.case_id,
            "document_id": case.document_id,
            "query": case.query,
            "expected": rel,
            "top5": ranked,
            "top5_scores": [round(r["score"], 4) for r in top],
            "hit1": metrics.hit_at_k(ranked, rel, 1),
            "hit5": metrics.hit_at_k(ranked, rel, top_k),
            "reciprocal_rank": metrics.reciprocal_rank(ranked, rel),
            "first_relevant_rank": first_rank,
            "all_relevant_ranks_in_top5": metrics.all_relevant_ranks(ranked, rel),
            "ambiguous": case.ambiguous,
        }
        if first_rank is None:
            full = search(store, case.query, _QueryAdapter, len(store.records))
            full_ranked = [r["chunk_id"] for r in full]
            record["full_rank_of_expected"] = {
                cid: (full_ranked.index(cid) + 1 if cid in full_ranked else None)
                for cid in rel
            }
        results.append(record)

    return {
        "hit1": sum(r["hit1"] for r in results),
        "hit5": sum(r["hit5"] for r in results),
        "mrr": metrics.mrr([r["reciprocal_rank"] for r in results]),
        "n_cases": len(results),
        "per_case": results,
    }
